"""Sandbox SQL executor — validates LLM-generated DDL/DML in an isolated Doris schema.

All SQL generated by design/drift-fix nodes runs through this sandbox
BEFORE being committed to the design plan or presented to humans.

The sandbox operates in a dedicated `wren_sandbox` schema:
  1. CREATE TABLE in sandbox
  2. EXPLAIN SELECT/INSERT to verify syntax
  3. DROP TABLE (cleanup)
  4. Return {valid, error, suggestion}

This catches: syntax errors, type mismatches, missing columns, invalid
DISTRIBUTED KEY, incompatible ALTER TABLE, etc.
"""

from __future__ import annotations

import asyncio
import logging
import re
from typing import Any

from wren_agent.config import settings

logger = logging.getLogger(__name__)


class SandboxSQL:
    """Doris sandbox for SQL validation.

    Creates tables in `wren_sandbox` schema, runs EXPLAIN/DRY-RUN,
    and cleans up immediately. Never writes to production schemas.
    """

    def __init__(self):
        self._sandbox_db = "wren_sandbox"
        self._client = None

    async def _ensure_client(self):
        """Lazy-init Doris client pointing to sandbox schema."""
        if self._client is None:
            from wren_agent.tools.doris_client import DorisClient
            self._client = DorisClient(database=self._sandbox_db)

    async def _ensure_sandbox_exists(self):
        """Ensure the sandbox database exists (create if not)."""
        await self._ensure_client()
        # Connect without database to create
        from wren_agent.tools.doris_client import DorisClient
        admin = DorisClient(
            host=settings.doris.host,
            port=settings.doris.query_port,
            user=settings.doris.user,
            password=settings.doris.password,
            database="information_schema",
        )
        try:
            await admin.execute(
                f"CREATE DATABASE IF NOT EXISTS {self._sandbox_db}"
            )
        except Exception:
            pass  # May already exist

    # ── DDL validation ───────────────────────────────────────

    async def validate_ddl(self, sql: str, table_name: str = "", drop: bool = True) -> dict[str, Any]:
        """Validate a CREATE TABLE or ALTER TABLE statement.

        Strategy: Execute in sandbox schema, then immediately DROP.
        Returns {valid, table, error, suggestion}.

        ``drop=False`` keeps the table — used by validate_design_plan(),
        which validates DML against the created tables and cleans up
        itself at the end.
        """
        await self._ensure_sandbox_exists()

        # Normalize SQL
        sql = sql.strip().rstrip(";")

        # Strip an explicit database prefix from the CREATE/ALTER target —
        # `CREATE TABLE db.table` bypasses the sandbox connection's default
        # database and creates the table in the REAL layer database (task
        # 63ce2059: every design round littered dws_ecommerce_orders_sh /
        # db_ads with empty DDL tables that also survived the cleanup DROP).
        sql = re.sub(
            r"(?i)((?:CREATE|ALTER)\s+TABLE\s+(?:IF\s+NOT\s+EXISTS\s+)?)"
            r"`?[\w$-]+`?\s*\.\s*",
            r"\1",
            sql,
        )

        try:
            from wren_agent.tools.doris_client import DorisClient
            sandbox = DorisClient(database=self._sandbox_db)

            # Execute the DDL (against the sandbox default database)
            await sandbox.execute(sql)

            # Extract table name if not provided
            if not table_name:
                table_name = self._extract_table_name(sql) or "unknown"
            # The sandbox-created table lives by its BARE name — a qualified
            # name wrapped in backticks makes the DROP target a single
            # non-existent identifier and the table lingers.
            bare = table_name.split(".")[-1].strip("`") or table_name

            # DROP the table immediately (batch mode keeps it for DML validation)
            if drop and "CREATE TABLE" in sql.upper():
                await sandbox.execute(f"DROP TABLE IF EXISTS `{bare}`")

            logger.info(f"Sandbox DDL valid: {table_name}")
            return {
                "valid": True,
                "table": table_name,
                "sql": sql[:200],
            }

        except Exception as e:
            error_msg = str(e)[:500]
            suggestion = self._suggest_fix(error_msg, sql)

            logger.warning(f"Sandbox DDL invalid ({table_name or '?'}): {error_msg[:120]}")
            return {
                "valid": False,
                "table": table_name,
                "error": error_msg,
                "suggestion": suggestion,
                "sql": sql[:200],
            }

    # ── DML / SELECT validation ──────────────────────────────

    async def validate_dml(self, sql: str, depends_tables: list[str] | None = None) -> dict[str, Any]:
        """Validate a SELECT or INSERT statement.

        Requires dependent tables to exist in sandbox (caller must create them first).
        Uses EXPLAIN to check syntax without executing.

        For INSERT: only EXPLAIN — never insert actual data.
        For SELECT: EXPLAIN only.
        """
        await self._ensure_sandbox_exists()

        sql = sql.strip().rstrip(";")

        # Check referenced tables exist (if we know them)
        if depends_tables:
            from wren_agent.tools.doris_client import DorisClient
            sandbox = DorisClient(database=self._sandbox_db)
            for tbl in depends_tables:
                exists = await sandbox.query_value(
                    "SELECT COUNT(*) FROM information_schema.tables "
                    "WHERE table_schema = %s AND table_name = %s",
                    (self._sandbox_db, tbl),
                )
                if not exists:
                    return {
                        "valid": False,
                        "error": f"Dependent table '{tbl}' does not exist in sandbox",
                        "suggestion": f"Create table '{tbl}' in sandbox first via validate_ddl()",
                        "sql": sql[:200],
                    }

        try:
            from wren_agent.tools.doris_client import DorisClient
            sandbox = DorisClient(database=self._sandbox_db)

            # Use EXPLAIN to validate syntax without execution
            explain_sql = f"EXPLAIN {sql}"
            result = await sandbox.query(explain_sql)

            return {
                "valid": True,
                "explain_rows": len(result),
                "sql": sql[:200],
            }

        except Exception as e:
            error_msg = str(e)[:500]
            suggestion = self._suggest_fix(error_msg, sql)

            return {
                "valid": False,
                "error": error_msg,
                "suggestion": suggestion,
                "sql": sql[:200],
            }

    # ── DataX JSON validation ────────────────────────────────

    async def validate_datax_json(self, json_str: str) -> dict[str, Any]:
        """Validate a DataX JSON configuration.

        Checks:
        - Valid JSON syntax
        - Required keys: job.setting, job.content[].reader, writer
        - Reader/writer names in known list
        - JDBC URL placeholders present
        """
        import json

        try:
            config = json.loads(json_str)
        except json.JSONDecodeError as e:
            return {
                "valid": False,
                "error": f"Invalid JSON: {e}",
                "suggestion": "Check JSON syntax — use json.dumps() or validate with a linter",
            }

        errors = []

        # Check required structure
        if "job" not in config:
            errors.append("Missing 'job' key")
        else:
            job = config["job"]
            if "setting" not in job:
                errors.append("Missing 'job.setting'")
            if "content" not in job or not isinstance(job["content"], list):
                errors.append("Missing 'job.content' array")
            elif not job["content"]:
                errors.append("'job.content' array is empty")
            else:
                for i, content in enumerate(job["content"]):
                    if "reader" not in content:
                        errors.append(f"content[{i}] missing 'reader'")
                    else:
                        reader = content["reader"]
                        if "name" not in reader:
                            errors.append(f"content[{i}].reader missing 'name'")

                        # Known reader types
                        valid_readers = [
                            "mysqlreader", "postgresqlreader", "oraclereader",
                            "dmreader", "dorisreader", "hdfsreader", "streamreader",
                        ]
                        if reader.get("name", "") not in valid_readers:
                            errors.append(
                                f"Unknown reader: {reader.get('name', '?')}. "
                                f"Valid: {valid_readers}"
                            )

                    if "writer" not in content:
                        errors.append(f"content[{i}] missing 'writer'")
                    else:
                        writer = content["writer"]
                        if "name" not in writer:
                            errors.append(f"content[{i}].writer missing 'name'")
                        elif writer.get("name") != "doriswriter":
                            errors.append(f"Expected 'doriswriter', got: {writer.get('name')}")

                        # Check for JDBC URL placeholder
                        if "parameter" in writer:
                            param = writer["parameter"]
                            jdbc = param.get("jdbcUrl", "")
                            if jdbc and "${" not in url_str(jdbc):
                                errors.append("Hardcoded JDBC URL — use ${writer_jdbc_url} placeholder")

        if errors:
            return {
                "valid": False,
                "error": "; ".join(errors[:5]),
                "suggestion": "Fix the listed issues and regenerate",
            }
        return {"valid": True, "reader": config["job"]["content"][0]["reader"]["name"]}

    # ── Batch: validate all SQL artifacts for a design plan ──

    async def validate_design_plan(
        self,
        plan: Any,
        *,
        layer: str | None = None,
        dml_mode: str = "explain",
    ) -> dict[str, Any]:
        """Validate SQL artifacts in a design plan.

        Args:
            plan: design plan with sql_artifacts
            layer: when set, only validate that layer (avoids re-checking
                upstream layers on every design_* call)
            dml_mode:
                ``explain`` — EXPLAIN DML in sandbox (business-db mode)
                ``skip`` — mark DML as skipped/valid (warehouse mode: load
                SQL references real layer DBs that are not in wren_sandbox)
        """
        sql_artifacts = getattr(plan, "sql_artifacts", []) or []
        if layer:
            layer_u = layer.upper()
            sql_artifacts = [
                a for a in sql_artifacts
                if str(getattr(a, "layer", "")).upper() == layer_u
            ]
        if not sql_artifacts:
            return {"total": 0, "passed": 0, "failed": 0, "skipped": 0, "results": []}

        results = []
        created_tables: set[str] = set()
        skipped = 0

        for artifact in sql_artifacts:
            result = {
                "layer": artifact.layer,
                "table": artifact.target_table,
                "sql_type": artifact.sql_type,
            }

            if artifact.sql_type == "DDL":
                r = await self.validate_ddl(artifact.sql, artifact.target_table, drop=False)
                result.update(r)
                if r["valid"] and r.get("table"):
                    created_tables.add(artifact.target_table)
            elif artifact.sql_type in ("DML_SELECT", "DML_INSERT", "DML_MERGE"):
                if dml_mode == "skip":
                    result.update({
                        "valid": True,
                        "skipped": True,
                        "error": "",
                        "suggestion": (
                            "DML sandbox EXPLAIN skipped — load SQL references "
                            "warehouse source databases outside wren_sandbox"
                        ),
                    })
                    skipped += 1
                else:
                    r = await self.validate_dml(
                        artifact.sql,
                        depends_tables=list(created_tables),
                    )
                    result.update(r)
            else:
                result["valid"] = True  # Skip unknown types

            results.append(result)

        passed = sum(1 for r in results if r.get("valid"))
        failed = sum(1 for r in results if not r.get("valid"))

        # Cleanup all created tables — bare names only (a backticked
        # qualified name fails the DROP and the table lingers in the real db;
        # task 63ce2059).
        from wren_agent.tools.doris_client import DorisClient
        sandbox = DorisClient(database=self._sandbox_db)
        for tbl in created_tables:
            bare = str(tbl).split(".")[-1].strip("`") or str(tbl)
            try:
                await sandbox.execute(f"DROP TABLE IF EXISTS `{bare}`")
            except Exception:
                pass

        return {
            "total": len(results),
            "passed": passed,
            "failed": failed,
            "skipped": skipped,
            "results": results,
        }

    # ── Helpers ──────────────────────────────────────────────

    def _extract_table_name(self, sql: str) -> str | None:
        """Extract table name from CREATE TABLE / ALTER TABLE."""
        # CREATE TABLE [IF NOT EXISTS] `table_name` ...
        m = re.search(
            r"(?:CREATE|ALTER)\s+TABLE\s+(?:IF\s+NOT\s+EXISTS\s+)?`?(\w+)`?",
            sql, re.IGNORECASE,
        )
        return m.group(1) if m else None

    def _suggest_fix(self, error: str, sql: str) -> str:
        """Generate a human-readable fix suggestion from error message."""
        error_lower = error.lower()

        if "replication num" in error_lower:
            return "Add PROPERTIES('replication_num'='1') to CREATE TABLE"
        elif "duplicate key" in error_lower or "primary key" in error_lower:
            return "Check DUPLICATE KEY / PRIMARY KEY columns exist in column list"
        elif "unknown column" in error_lower:
            col_name = re.search(r"Unknown column ['`](\w+)['`]", error, re.IGNORECASE)
            if col_name:
                return f"Column '{col_name.group(1)}' not found in table — check spelling or add to column list"
            return "Referenced column does not exist — check column list"
        elif "syntax error" in error_lower:
            return "SQL syntax error — check commas, quotes, and keywords"
        elif "type" in error_lower and "incompatible" in error_lower:
            return "Type mismatch — check Doris type compatibility in TYPE_MAPPING"
        elif "already exists" in error_lower:
            return "Table already exists in sandbox (race condition) — retry"
        return "Review the error message and fix the SQL accordingly"


def url_str(val) -> str:
    """Extract string value from a variable that could be string or dict."""
    if isinstance(val, str):
        return val
    return str(val)


# ── Convenience: inject sandbox into node ───────────────────────


async def validate_node_sql(state, node_name: str) -> int:
    """Validate SQL artifacts generated by a design node.

    Only the current layer is checked (``design_dws`` → DWS artifacts).
    Warehouse mode skips DML EXPLAIN — load SQL references real layer
    databases that are not present in ``wren_sandbox``.

    Returns number of failed validations.
    """
    from wren_agent.tools.event_emitter import emit_warning

    plan = state.get("design_plan")
    if not plan:
        return 0

    layer = node_name.removeprefix("design_").upper()
    warehouse = state.get("source_mode") == "warehouse"
    sandbox = SandboxSQL()
    result = await sandbox.validate_design_plan(
        plan,
        layer=layer,
        dml_mode="skip" if warehouse else "explain",
    )

    if result["total"] == 0:
        return 0

    skipped = int(result.get("skipped") or 0)
    if result["failed"] > 0:
        state["warnings"] = state.get("warnings", []) + [
            f"[Sandbox] {node_name}: {result['failed']}/{result['total']} SQL artifacts INVALID"
        ]
        # Persist per-artifact failure details (capped) so the dashboard
        # "technical details" shows the real Doris error per table, not just
        # the N/M summary line. WS events below stay as the live feed.
        max_details = 10
        detail_lines = []
        for r in result["results"]:
            if r.get("valid"):
                continue
            if len(detail_lines) < max_details:
                table = r.get("table", "?")
                error = (r.get("error", "?") or "?")[:300]
                detail_lines.append(f"[Sandbox] {layer}.{table}: {error}")
        remaining = result["failed"] - len(detail_lines)
        if remaining > 0:
            detail_lines.append(f"[Sandbox] ... ({remaining} more failures omitted)")
        if detail_lines:
            state["warnings"] = state.get("warnings", []) + detail_lines
        for r in result["results"]:
            if not r.get("valid"):
                emit_warning(state,
                    f"SQL Sandbox Fail [{r['table']}]: {r.get('error','?')[:120]}")
    else:
        skip_note = f" ({skipped} DML skipped)" if skipped else ""
        state["warnings"] = state.get("warnings", []) + [
            f"[Sandbox] {node_name}: {result['passed']}/{result['total']} "
            f"SQL artifacts valid{skip_note}"
        ]

    return result["failed"]
